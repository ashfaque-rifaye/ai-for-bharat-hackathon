def add_translations_to_file(filepath: str, translations: dict) -> bool:
    """Add new language keys to all MultiLangText fields in a scheme file."""
    with open(filepath, "r", encoding="utf-8") as f:
        scheme = json.load(f)

    scheme_id = scheme.get("schemeId")
    if scheme_id not in translations:
        print(f"  ⚠️  No translations for {scheme_id}, skipping")
        return False

    trans = translations[scheme_id]
    changed = False

    # Add to top-level fields: name, description, shortDescription
    for field in ("name", "description", "shortDescription"):
        if field in scheme and isinstance(scheme[field], dict) and field in trans:
            for lang_code, text in trans[field].items():
                if lang_code not in scheme[field]:
                    scheme[field][lang_code] = text
                    changed = True

    # Add to eligibility.description if it exists
    if "eligibility" in scheme and "description" in scheme.get("eligibility", {}):
        elig_desc = scheme["eligibility"]["description"]
        if isinstance(elig_desc, dict) and "description" in trans:
            # Use a shortened version of the main description for eligibility
            pass  # eligibility desc is different, keep existing

    # Add to benefits.description if it exists
    if "benefits" in scheme and isinstance(scheme["benefits"], dict):
        ben_desc = scheme["benefits"].get("description", {})
        if isinstance(ben_desc, dict) and "shortDescription" in trans:
            for lang_code, text in trans["shortDescription"].items():
                if lang_code not in ben_desc:
                    ben_desc[lang_code] = text
                    changed = True

    if changed:
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(scheme, f, ensure_ascii=False, indent=2)
        print(f"  ✅ Updated {scheme_id}")
    else:
        print(f"  ℹ️  {scheme_id} already up to date")

    return changed


def main():
    json_files = sorted(glob.glob(os.path.join(SEED_DIR, "*.json")))
    print(f"Found {len(json_files)} scheme files\n")

    updated = 0
    for filepath in json_files:
        if add_translations_to_file(filepath, TRANSLATIONS):
            updated += 1

    print(f"\n🎉 Updated {updated}/{len(json_files)} scheme files with 5 new languages")


if __name__ == "__main__":
    main()
